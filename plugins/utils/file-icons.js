export function fileTypeIcon(path) {
    const name = path.split(/[\\/]/).pop().toLowerCase();
    const extension = name.split(".").pop();
    return Object.hasOwn(fileTypeIcons, extension) ? fileTypeIcons[extension] : undefined;
}
